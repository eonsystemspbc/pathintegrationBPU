#!/usr/bin/env python3
"""Fleet launcher for the plume-tracking REGRESSION benchmark (72 runs, 6 seeds)."""
from __future__ import annotations

import argparse, os, re, subprocess, sys
from pathlib import Path

EPOCHS, PATIENCE, SEEDS = 30, 6, 6
FLEET_SIZE = 16
S3_PREFIX = "pathint-exp08-regression"
N_RUNS = 72   # 5 arms x 2 io x 6 seeds + 2 refs x 6 seeds

HERE = Path(__file__).resolve().parent
REPO_ROOT = next(p for p in HERE.parents if (p / "pyproject.toml").exists())
AL = REPO_ROOT / "docs" / "results" / "antennal_lobe_gas"
FLEET_DIR = REPO_ROOT / "scott" / "aws_fleet"
BASE_CONFIG = FLEET_DIR / "config.env"
GEN_CONFIG = HERE / "fleet_config.env"

EXP_RUN_SCRIPT = "docs/results/regression_plume_tracking/run_regression.py"
EXP_OUTPUT_DIR = "docs/results/regression_plume_tracking/fleet_outputs"


def substrate_files() -> list[str]:
    """The AL substrate + operators live in the antennal_lobe_gas folder (git-ignored), so they
    must be staged to S3 for the workers."""
    files = []
    for pat in ("*.npz", "*.npy", "*.json"):
        files += sorted((AL / "substrate").glob(pat))
        files += sorted((AL / "substrate" / "operators").glob(pat))
    return [str(f.relative_to(REPO_ROOT)) for f in files]


def exp_args() -> str:
    return f"--device cuda --epochs {EPOCHS} --patience {PATIENCE} --seeds 0 1 2 3 4 5"


def write_config() -> None:
    subs = substrate_files()
    missing = [f for f in subs if not (REPO_ROOT / f).exists()]
    if missing:
        sys.exit("missing substrate files:\n  " + "\n  ".join(missing))
    ov = {"S3_PREFIX": S3_PREFIX, "FLEET_SIZE": str(FLEET_SIZE), "WORKERS_PER_INSTANCE": "1",
          "EXP_RUN_SCRIPT": EXP_RUN_SCRIPT, "EXP_OUTPUT_DIR": EXP_OUTPUT_DIR,
          "EXP_ARGS": exp_args(), "SUBSTRATE_FILES": " ".join(subs)}
    seen, out = set(), ["# GENERATED by run.py", ""]
    for line in BASE_CONFIG.read_text().splitlines():
        m = re.match(r"^export (\w+)=", line)
        if m and m.group(1) in ov:
            out.append(f'export {m.group(1)}="{ov[m.group(1)]}"'); seen.add(m.group(1))
        else:
            out.append(line)
    for k, v in ov.items():
        if k not in seen:
            out.append(f'export {k}="{v}"')
    GEN_CONFIG.write_text("\n".join(out) + "\n")


def sh(script, *a):
    env = os.environ.copy(); env["FLEET_CONFIG"] = str(GEN_CONFIG)
    return subprocess.run(["bash", str(FLEET_DIR / script), *a], env=env).returncode


def main(argv=None):
    ap = argparse.ArgumentParser()
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--status", action="store_true"); g.add_argument("--collect", action="store_true")
    g.add_argument("--stop", action="store_true"); g.add_argument("--log", action="store_true")
    ap.add_argument("--yes", "-y", action="store_true")
    a = ap.parse_args(argv)
    write_config()
    if a.status:
        return sh("status.sh")
    if a.log:
        return sh("watch.sh", "-f")
    if a.stop:
        return sh("stop.sh")
    if a.collect:
        if (rc := sh("collect.sh")) != 0:
            return rc
        return subprocess.run(["uv", "run", "python", str(HERE / "run_regression.py"),
                               "--analyze-only", "--output-dir", EXP_OUTPUT_DIR],
                              cwd=str(REPO_ROOT)).returncode
    print(f"Plume-tracking REGRESSION: {N_RUNS} runs, {FLEET_SIZE} GPUs, ~$3-6")
    if (rc := sh("stage_data.sh")) != 0:
        return rc
    return sh("launch_fleet.sh")


if __name__ == "__main__":
    raise SystemExit(main())
