#!/usr/bin/env python3
"""run.py -- one-command launcher for Experiment 7 (Antennal Lobe x turbulent gas detection)
on the AWS spot-GPU fleet. Pins every parameter as a frozen record and drives the validated
scott/aws_fleet harness through a generated run-specific fleet_config.env.

Usage (repo root; `uv run python` here):
  uv run python docs/results/antennal_lobe_gas/run.py            stage + launch (confirms spend)
    --yes       skip the confirmation prompt
    --log       follow live
    --status    one-shot progress snapshot
    --collect   pull results from S3, concatenate shards, analyse, regenerate figures
    --stop      terminate ALL fleet instances now
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

# ------------------------------------------------------------------ run knobs (frozen record)
EPOCHS = 30
PATIENCE = 6
BATCH = 128
LR = 3e-3
LEAK = 0.3
SEEDS = 3                 # connectome training replicates / independent control graphs
FRACTIONS = (5, 10, 25, 50, 100)
FLEET_SIZE = 16           # instances = shards (each 1 GPU). Bigger = less wall-clock, ~flat cost.
S3_PREFIX = "pathint-exp07-antennal-gas"
N_RUNS = 195              # 150 standard + 30 graded_ln + 15 adapter_only
# ------------------------------------------------------------------------------ plumbing
HERE = Path(__file__).resolve().parent
REPO_ROOT = next(p for p in HERE.parents if (p / "pyproject.toml").exists())
FLEET_DIR = REPO_ROOT / "scott" / "aws_fleet"
BASE_CONFIG = FLEET_DIR / "config.env"
GEN_CONFIG = HERE / "fleet_config.env"
FIG_SCRIPT = HERE / "make_figures.py"
SUBSTRATE = HERE / "substrate"

EXP_RUN_SCRIPT = "docs/results/antennal_lobe_gas/run_experiment.py"
EXP_OUTPUT_DIR = "docs/results/antennal_lobe_gas/fleet_outputs"


def substrate_files() -> list[str]:
    """All substrate inputs the workers need, as repo-relative paths (staged to S3 separately
    because outputs/ is gitignored so they don't ride in the code tarball)."""
    files = []
    for pat in ("*.npz", "*.npy", "*.json"):
        files += sorted(SUBSTRATE.glob(pat))
        files += sorted((SUBSTRATE / "operators").glob(pat))
    return [str(f.relative_to(REPO_ROOT)) for f in files]


def exp_args() -> str:
    return (f"--device cuda --epochs {EPOCHS} --patience {PATIENCE} --batch-size {BATCH} "
            f"--lr {LR} --leak {LEAK} --seeds 0 1 2 --fractions {' '.join(map(str, FRACTIONS))}")


def write_config() -> None:
    if not BASE_CONFIG.exists():
        sys.exit(f"base config not found: {BASE_CONFIG}")
    subs = substrate_files()
    missing = [f for f in subs if not (REPO_ROOT / f).exists()]
    if missing:
        sys.exit("substrate files missing (build them first):\n  " + "\n  ".join(missing))
    overrides = {
        "S3_PREFIX": S3_PREFIX,
        "FLEET_SIZE": str(FLEET_SIZE),
        "WORKERS_PER_INSTANCE": "1",
        "EXP_RUN_SCRIPT": EXP_RUN_SCRIPT,
        "EXP_OUTPUT_DIR": EXP_OUTPUT_DIR,
        "EXP_ARGS": exp_args(),
        "SUBSTRATE_FILES": " ".join(subs),
    }
    seen: set[str] = set()
    out = ["# GENERATED by run.py -- edit the constants in run.py instead.", ""]
    for line in BASE_CONFIG.read_text().splitlines():
        m = re.match(r"^export (\w+)=", line)
        if m and m.group(1) in overrides:
            out.append(f'export {m.group(1)}="{overrides[m.group(1)]}"'); seen.add(m.group(1))
        else:
            out.append(line)
    for k, v in overrides.items():
        if k not in seen:
            out.append(f'export {k}="{v}"')
    GEN_CONFIG.write_text("\n".join(out) + "\n")


def sh(script: str, *a: str) -> int:
    env = os.environ.copy(); env["FLEET_CONFIG"] = str(GEN_CONFIG)
    return subprocess.run(["bash", str(FLEET_DIR / script), *a], env=env).returncode


def banner() -> str:
    spot = min(FLEET_SIZE, 16); od = max(FLEET_SIZE - spot, 0)
    return (
        "============================================================\n"
        " Experiment 7 - Antennal Lobe x turbulent target-gas detection\n"
        "============================================================\n"
        "  substrate    : FlyWire-783 antennal lobe (N=3499: 2282 ORN / 429 LN / 685 PN + 103 thermo/hygro)\n"
        "  task         : UCI-309 ethylene detection in turbulent Me/CO mixtures; train MED/HIGH, TEST LOW conc\n"
        "  model        : leaky-tanh RNN, connectome recurrence, sensor->glomerulus adapter -> ORN, PN readout\n"
        "  io           : bio (biological ports) + generic (free all-N I/O)\n"
        "  arms         : connectome / degree / random (sparse, param-matched) + spectrum / dense (dense ref)\n"
        "  controls     : degree-preserving, ER-random, eigenvalue-spectrum-matched, dense-Gaussian; rho=0.95\n"
        f"  variants     : standard + graded-LN (connectome/degree) ; adapter-only floor\n"
        f"  seeds        : {SEEDS}   fractions: {FRACTIONS}   epochs: {EPOCHS} (patience {PATIENCE})\n"
        f"  total plan   : {N_RUNS} runs\n"
        f"  fleet        : {FLEET_SIZE} GPUs (~{spot} spot + ~{od} on-demand), g6.xlarge (L4 24GB)\n"
        f"  est. cost    : ~$3-8 (tiny model; ~20-30 min wall incl. boot)\n"
        f"  S3 area      : s3://<bucket>/{S3_PREFIX}/   local: {EXP_OUTPUT_DIR}/\n"
        "============================================================"
    )


def launch(skip: bool) -> int:
    print(banner())
    if not skip:
        try:
            ans = input("Stage to S3 and launch the fleet? This spends money. [y/N] ").strip().lower()
        except EOFError:
            ans = ""
        if ans not in ("y", "yes"):
            print("Aborted."); return 1
    print("\n[1/2] staging ...")
    if (rc := sh("stage_data.sh")) != 0:
        return rc
    print("\n[2/2] launching ...")
    if (rc := sh("launch_fleet.sh")) != 0:
        return rc
    rel = "docs/results/antennal_lobe_gas/run.py"
    print(f"\nLaunched. Next:\n  uv run python {rel} --status\n  uv run python {rel} --log\n"
          f"  uv run python {rel} --collect   # when finished")
    return 0


def status() -> int:
    rc = sh("status.sh")
    snip = ('source "$FLEET_CONFIG"; aws s3 ls "$S3_URI/outputs/" --region "$AWS_REGION" '
            '--recursive 2>/dev/null | grep -E "result_shard[0-9]+.json" || true')
    env = os.environ.copy(); env["FLEET_CONFIG"] = str(GEN_CONFIG)
    out = subprocess.run(["bash", "-c", snip], env=env, capture_output=True, text=True).stdout
    print(f"\n=== Exp 7 progress ===\n  shards finished: {len(out.splitlines())} / {FLEET_SIZE}")
    return rc


def collect() -> int:
    if (rc := sh("collect.sh")) != 0:
        return rc
    print("analysing ...")
    subprocess.run(["uv", "run", "python", str(HERE / "run_experiment.py"),
                    "--analyze-only", "--output-dir", EXP_OUTPUT_DIR], cwd=str(REPO_ROOT))
    print("figures ...")
    return subprocess.run(["uv", "run", "python", str(FIG_SCRIPT), EXP_OUTPUT_DIR],
                          cwd=str(REPO_ROOT)).returncode


def stop(skip: bool) -> int:
    if not skip:
        try:
            ans = input("Terminate ALL fleet instances now? [y/N] ").strip().lower()
        except EOFError:
            ans = ""
        if ans not in ("y", "yes"):
            print("Aborted."); return 1
    return sh("stop.sh")


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Exp 7 fleet launcher.")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--log", action="store_true")
    g.add_argument("--status", action="store_true")
    g.add_argument("--collect", action="store_true")
    g.add_argument("--stop", action="store_true")
    ap.add_argument("--yes", "-y", action="store_true")
    a = ap.parse_args(argv)
    write_config()
    if a.log:
        return sh("watch.sh", "-f")
    if a.status:
        return status()
    if a.collect:
        return collect()
    if a.stop:
        return stop(a.yes)
    return launch(a.yes)


if __name__ == "__main__":
    raise SystemExit(main())
