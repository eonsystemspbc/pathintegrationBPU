#!/usr/bin/env python3
"""Fleet launcher for the AL ROW of the 4x4 region x task matrix (4 regions x 3 arms x 6 seeds)."""
from __future__ import annotations
import argparse, os, re, subprocess, sys
from pathlib import Path

SEEDS, FLEET_SIZE = 5, 18
S3_PREFIX = "pathint-exp10-alrow"
N_RUNS = 35

HERE = Path(__file__).resolve().parent
REPO_ROOT = next(p for p in HERE.parents if (p / "pyproject.toml").exists())
AL = REPO_ROOT / "docs/results/antennal_lobe_gas"
FLEET_DIR = REPO_ROOT / "scott/aws_fleet"
BASE_CONFIG = FLEET_DIR / "config.env"
GEN_CONFIG = HERE / "fleet_config.env"
EXP_RUN_SCRIPT = "docs/results/region_task_4x4/run_al_row.py"
EXP_OUTPUT_DIR = "docs/results/region_task_4x4/al_row_outputs"


def substrate_files():
    f = [HERE / "al_prepared_unsigned.npz",
         REPO_ROOT / "connectomes/flywire_antennal_lobe/adjacency_unsigned.npz",
         REPO_ROOT / "connectomes/flywire_antennal_lobe/graph_metadata.json",
         REPO_ROOT / "connectomes/flywire_antennal_lobe/pool_assignments.csv"]
    return [str(p.relative_to(REPO_ROOT)) for p in f if p.exists()]


def write_config():
    subs = substrate_files()
    ov = {"S3_PREFIX": S3_PREFIX, "FLEET_SIZE": str(FLEET_SIZE), "WORKERS_PER_INSTANCE": "1",
          "EXP_RUN_SCRIPT": EXP_RUN_SCRIPT, "EXP_OUTPUT_DIR": EXP_OUTPUT_DIR,
          "EXP_ARGS": "--device cuda --mqar-seeds 0 1 2 3 4 --flow-seeds 0 1 2 --path-seeds 0 1 2",
          "SUBSTRATE_FILES": " ".join(subs)}
    seen, out = set(), ["# GENERATED by run.py", ""]
    for line in BASE_CONFIG.read_text().splitlines():
        m = re.match(r"^export (\w+)=", line)
        if m and m.group(1) in ov:
            out.append(f'export {m.group(1)}="{ov[m.group(1)]}"'); seen.add(m.group(1))
        else:
            out.append(line)
    for k, v in ov.items():
        if k not in seen: out.append(f'export {k}="{v}"')
    GEN_CONFIG.write_text("\n".join(out) + "\n")
    print(f"staging {len(subs)} substrate files")


def sh(s, *a):
    env = os.environ.copy(); env["FLEET_CONFIG"] = str(GEN_CONFIG)
    return subprocess.run(["bash", str(FLEET_DIR / s), *a], env=env).returncode


def main(argv=None):
    ap = argparse.ArgumentParser(); g = ap.add_mutually_exclusive_group()
    g.add_argument("--status", action="store_true"); g.add_argument("--collect", action="store_true")
    g.add_argument("--stop", action="store_true")
    a = ap.parse_args(argv); write_config()
    if a.status: return sh("status.sh")
    if a.stop: return sh("stop.sh")
    if a.collect:
        if (rc := sh("collect.sh")) != 0: return rc
        return subprocess.run(["uv","run","python",str(HERE/"run_al_row.py"),
                               "--analyze-only","--output-dir",EXP_OUTPUT_DIR], cwd=str(REPO_ROOT)).returncode
    print(f"AL ROW: {N_RUNS} runs on {FLEET_SIZE} GPUs")
    if (rc := sh("stage_data.sh")) != 0: return rc
    return sh("launch_fleet.sh")

if __name__ == "__main__":
    raise SystemExit(main())
