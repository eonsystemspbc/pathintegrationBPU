#!/usr/bin/env python3
"""run.py - Experiment 3, SUBRUN 01: dense_c3_core learning-rate sweep (hypothesis validation).

The main Exp-3 run trained every control at the connectome's optimum lr=1e-3 (no sweep). The first
arm to finish, `dense_c3_core` (the smaller dense param-matched net, 873 neurons), reached only
test_acc ~0.17 -- far below the connectome's 0.881 and below every Exp-2 control. That looked like
under-tuning, not a real result: lr=1e-3 was tuned for the SPARSE connectome, and Exp 2's dense
surrogate `eigvec_matched_core` had preferred lr=3e-3. A fully-trainable dense net scoring below
even a frozen-reservoir net is the signature of a bad lr, not a capacity limit.

This subrun tests that directly: sweep `dense_c3_core` over additional learning rates and see whether
accuracy jumps. lr=1e-3 (20 seeds) is REUSED from the main run (`port_c3_1e3.py`); this run trains the
four NEW lrs {1e-4, 3e-4, 3e-3, 1e-2} x 20 seeds = 80 runs. Combined, that is the full
{1e-4, 3e-4, 1e-3, 3e-3, 1e-2} sweep, best-lr-per-unit. If a different lr lifts dense_c3_core well
above 0.17, the single-lr main run is confirmed unfair to the dense controls and we re-sweep all of
them (subrun 02); if 0.17 holds across lrs, it is a genuine capacity result.

Drives the shared engine `../../run_experiment.py --kinds c3 --substrates core --lr-grid ...` so the
task / model / budget are identical to the main run. patience OFF, 300-epoch cap, converged-stop kept.
Every parameter is pinned below; this file is the frozen record of subrun 01.

Usage (from the repo root):
  R=scott/experiment_03_dense_param_matched/subruns/01_dense_c3_lr_sweep/run.py
  uv run python $R            # stage + launch (confirms spend)
  uv run python $R --status   # progress vs the 80-run plan
  uv run python $R --log      # follow live
  uv run python $R --collect  # pull results, reuse the 1e-3 arm, analyze
  uv run python $R --stop     # terminate the fleet
"""
from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

# ----------------------------------------------------------------------------- run knobs
EPOCHS = 300
PATIENCE = EPOCHS              # plateau-stop OFF (= epoch cap); converged-stop (val>=0.995) kept
NEW_LRS = ["1e-4", "3e-4", "3e-3", "1e-2"]   # the lrs to TRAIN here; 1e-3 is reused from the main run
FULL_GRID = ["1e-4", "3e-4", "1e-3", "3e-3", "1e-2"]  # for the record (analysis combines all five)
C3_SEEDS = 20                  # match the reused 1e-3 arm's 20 seeds
KINDS = "c3"
SUBSTRATE = "core"
FLEET_SIZE = 20                # 80 runs / 20 GPUs ~= 4 each; dense_c3_core is cheap (~14 min/run)
MATRIX = "connectomes/flywire_mushroom_body/adjacency_unsigned.npz"
S3_PREFIX = "pathint-exp03-c3lr"        # isolated S3 area for this subrun
# ------------------------------------------------------------------------------ plumbing
HERE = Path(__file__).resolve().parent                       # .../subruns/01_dense_c3_lr_sweep
EXP_ROOT = HERE.parents[1]                                   # .../experiment_03_dense_param_matched
REPO_ROOT = EXP_ROOT.parents[1]
FLEET_DIR = REPO_ROOT / "scott" / "aws_fleet"
BASE_CONFIG = FLEET_DIR / "config.env"
GEN_CONFIG = HERE / "fleet_config.env"
PORT_SCRIPT = HERE / "port_c3_1e3.py"
CORE_INDICES = EXP_ROOT / "substrate" / "core_indices.npy"

EXP_RUN_SCRIPT = "scott/experiment_03_dense_param_matched/run_experiment.py"
EXP_OUTPUT_DIR = "scott/experiment_03_dense_param_matched/subruns/01_dense_c3_lr_sweep/outputs"
N_RUNS = C3_SEEDS * len(NEW_LRS)


def exp_args() -> str:
    return (
        f"--matrix {MATRIX} --device cuda --epochs {EPOCHS} --patience {PATIENCE} "
        f"--kinds {KINDS} --substrates {SUBSTRATE} --c3-seeds {C3_SEEDS} "
        f"--lr-grid {' '.join(NEW_LRS)}"
    )


def write_config() -> None:
    if not BASE_CONFIG.exists():
        sys.exit(f"base config not found: {BASE_CONFIG}")
    if not CORE_INDICES.exists():
        sys.exit(f"MB-core index artifact missing: {CORE_INDICES}")
    overrides = {
        "S3_PREFIX": S3_PREFIX,
        "FLEET_SIZE": str(FLEET_SIZE),
        "WORKERS_PER_INSTANCE": "1",
        "EXP_RUN_SCRIPT": EXP_RUN_SCRIPT,
        "EXP_OUTPUT_DIR": EXP_OUTPUT_DIR,
        "EXP_ARGS": exp_args(),
        "SUBSTRATE_FILES": MATRIX,
    }
    seen: set[str] = set()
    out_lines = ["# GENERATED by run.py - do not hand-edit; edit the constants in run.py instead.",
                 "# Overrides aws_fleet/config.env for Experiment 3, subrun 01 (dense_c3_core lr sweep).", ""]
    for line in BASE_CONFIG.read_text().splitlines():
        m = re.match(r'^export (\w+)=', line)
        if m and m.group(1) in overrides:
            out_lines.append(f'export {m.group(1)}="{overrides[m.group(1)]}"')
            seen.add(m.group(1))
        else:
            out_lines.append(line)
    for key, val in overrides.items():
        if key not in seen:
            out_lines.append(f'export {key}="{val}"')
    GEN_CONFIG.write_text("\n".join(out_lines) + "\n")


def sh(script: str, *args: str) -> int:
    env = os.environ.copy()
    env["FLEET_CONFIG"] = str(GEN_CONFIG)
    return subprocess.run(["bash", str(FLEET_DIR / script), *args], env=env).returncode


def plan_banner() -> str:
    return (
        "============================================================\n"
        " Experiment 3 - SUBRUN 01: dense_c3_core learning-rate sweep\n"
        "============================================================\n"
        f"  hypothesis        : dense_c3_core's ~0.17 at lr=1e-3 is an lr artifact, not a capacity limit\n"
        f"  condition         : dense_c3_core only (873-neuron dense, param-matched to the 5.6k core)\n"
        f"  NEW lrs (trained) : {', '.join(NEW_LRS)}   x {C3_SEEDS} seeds = {N_RUNS} runs\n"
        f"  reused            : lr=1e-3 x {C3_SEEDS} seeds (from the main run, via port_c3_1e3.py)\n"
        f"  full sweep        : {', '.join(FULL_GRID)}  (best-lr-per-unit at analysis)\n"
        f"  budget            : {EPOCHS}-epoch cap, plateau patience OFF (={PATIENCE}), converged-stop kept\n"
        f"  fleet             : {FLEET_SIZE} GPUs (dense_c3_core ~14 min/run -> ~1 h wall-clock)\n"
        f"  S3 area           : s3://<bucket>/{S3_PREFIX}/  (isolated)\n"
        f"  local results dir : {EXP_OUTPUT_DIR}/\n"
        "  est. cost         : ~5 GPU-hr -> a few dollars\n"
        "============================================================"
    )


def launch(skip_confirm: bool) -> int:
    print(plan_banner())
    if not skip_confirm:
        try:
            ans = input("Stage to S3 and launch the fleet? This spends money. [y/N] ").strip().lower()
        except EOFError:
            ans = ""
        if ans not in ("y", "yes"):
            print("Aborted (nothing launched). Re-run with --yes to skip this prompt.")
            return 1
    print("\n[1/2] staging code + substrate to S3 ...")
    if (rc := sh("stage_data.sh")) != 0:
        return rc
    print("\n[2/2] launching the fleet ...")
    if (rc := sh("launch_fleet.sh")) != 0:
        return rc
    rel = "scott/experiment_03_dense_param_matched/subruns/01_dense_c3_lr_sweep/run.py"
    print(f"\nLaunched. Next:\n  uv run python {rel} --status\n  uv run python {rel} --collect")
    return 0


def stop(skip_confirm: bool) -> int:
    if not skip_confirm:
        print("This terminates ALL running fleet instances (tag project=pathint).")
        try:
            ans = input("Terminate the fleet now? [y/N] ").strip().lower()
        except EOFError:
            ans = ""
        if ans not in ("y", "yes"):
            print("Aborted.")
            return 1
    return sh("stop.sh")


def status() -> int:
    rc = sh("status.sh")
    snippet = ('source "$FLEET_CONFIG"; '
               'aws s3 ls "$S3_URI/outputs/runs/" --region "$AWS_REGION" --recursive 2>/dev/null '
               '| grep "result.json" || true')
    env = os.environ.copy()
    env["FLEET_CONFIG"] = str(GEN_CONFIG)
    out = subprocess.run(["bash", "-c", snippet], env=env, capture_output=True, text=True).stdout
    print(f"\n=== Subrun 01 progress ({N_RUNS} new runs planned; 1e-3 reused) ===")
    print(f"  finished : {len(out.splitlines())} / {N_RUNS}")
    return rc


def collect() -> int:
    if (rc := sh("collect.sh")) != 0:
        return rc
    print("\nreusing the main run's lr=1e-3 dense_c3_core arm ...")
    subprocess.run(["uv", "run", "python", str(PORT_SCRIPT)], cwd=str(REPO_ROOT))
    print("running analysis (combined 5-lr sweep, best-lr-per-unit) ...")
    return subprocess.run(["uv", "run", "python", str(EXP_ROOT / "run_experiment.py"),
                           "--analyze-only", "--output-dir", EXP_OUTPUT_DIR], cwd=str(REPO_ROOT)).returncode


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="Experiment 3 subrun 01 launcher (dense_c3_core lr sweep).")
    g = ap.add_mutually_exclusive_group()
    g.add_argument("--log", action="store_true")
    g.add_argument("--status", action="store_true")
    g.add_argument("--collect", action="store_true")
    g.add_argument("--stop", action="store_true")
    ap.add_argument("--yes", "-y", action="store_true")
    args = ap.parse_args(argv)
    write_config()
    if args.log:
        return sh("watch.sh", "-f")
    if args.status:
        return status()
    if args.collect:
        return collect()
    if args.stop:
        return stop(skip_confirm=args.yes)
    return launch(skip_confirm=args.yes)


if __name__ == "__main__":
    raise SystemExit(main())
